const rep = <T>(n: number, ...items: T[]): T[] => Array.from({ length: n }, () => items).flat();

/**
 * One bar of a fingerstyle triplet pattern (Romanza): per beat the melody on the high e string,
 * then the B and G strings; the bass sounds with the first note.
 */
function triplets(bass: string, melody: [number, number, number], inner: [number, number]): string {
  const beats = melody.map((m, i) => {
    const top = i === 0 ? `(${m}.1 ${bass})` : `${m}.1`;
    return `${top}{tu 3} ${inner[0]}.2{tu 3} ${inner[1]}.3{tu 3}`;
  });
  return `tex::8 ${beats.join(' ')}`;
}

/** Four triplet-eighth arpeggios of a three-note chord, with a bass note on the first (Moonlight). */
function arp4(bass: string, a: string, b: string, c: string, a2 = a, b2 = b, c2 = c): string {
  const t = (x: string, y: string, z: string, low?: string) => `${low ? `${low}+` : ''}${x}:8t ${y}:8t ${z}:8t`;
  return [t(a, b, c, bass), t(a, b, c), t(a2, b2, c2), t(a2, b2, c2)].join(' ');
}

